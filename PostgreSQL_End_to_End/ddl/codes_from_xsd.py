#!/usr/bin/env python3
"""Write ddl/09_codes.sql: the listed codes of the FundsXML schema the loader checks.

    python ddl/codes_from_xsd.py path/to/FundsXML.xsd > ddl/09_codes.sql

Run it again for every new schema version; the codes are stored per version, so a code from a
newer version than the one a sender declares can be recognised as such.
"""
import sys

from lxml import etree

XS = "{http://www.w3.org/2001/XMLSchema}"
# (list name, element, the complex type it is declared in; None = anywhere)
LISTS = [("DataOperation", "DataOperation", None), ("PriceNature", "PriceNature", None),
         ("TotalAssetNature", "TotalAssetNature", None), ("DocumentType", "ListedType", "DocumentType"),
         ("FlowType", "TransactionType", "FlowType"), ("TransactionKind", "TransactionKind", "TransactionType"),
         ("EarningKind", "EarningKind", "EarningType")]


def main(xsd):
    tree = etree.parse(xsd)
    root = tree.getroot()
    version = root.get("version") or "4.2.9"
    named = {t.get("name"): t for t in root.iter(XS + "simpleType") if t.get("name")}
    rows = []
    for name, element, within in LISTS:
        codes = set()
        for el in root.iter(XS + "element"):
            if el.get("name") != element:
                continue
            owner = next((a.get("name") for a in el.iterancestors(XS + "complexType") if a.get("name")), None)
            if within and owner != within:
                continue
            t = named.get((el.get("type") or "").split(":")[-1])
            for src in (el, t):
                if src is not None:
                    codes.update(e.get("value") for e in src.iter(XS + "enumeration"))
        rows += [(name, c) for c in sorted(codes)]
    print(f"-- Generated by ddl/codes_from_xsd.py from FundsXML {version}. Do not edit.")
    print("INSERT INTO code_list (list, code, schema_version) VALUES")
    print(",\n".join(f"  ('{n}', '{c.replace(chr(39), chr(39) * 2)}', '{version}')" for n, c in rows) + ";")


if __name__ == "__main__":
    main(sys.argv[1])
