#!/usr/bin/env python3
"""Write the input deliveries of the PostgreSQL end-to-end example (synthetic, deterministic).

    python data/make_samples.py            writes data/in/*.xml and data/bad/*.xml

The deliveries come from one fictional asset manager (EXAMPLE-AM) and use the same funds as
the realistic samples (../FundsXML_Files/4.2.9/realistic/make_realistic.py, imported here),
arranged so that every repeating node of FundsXML really repeats:

  01  month end 2025-10-31: an umbrella with two subfunds and two single funds in ONE file;
      share classes in EUR, USD and CHF; a daily NAV history per share class; portfolios with
      positions, transactions, income and a look-through; asset master data shared by all
      funds; EMT and TPT; an EET per share class
  02  daily NAVs 2025-11-03..05: every fund and share class, an ESTIMATED and an OFFICIAL NAV
      per day, net assets in share-class and fund currency
  03  documents: prospectus as a link, KIDs in two languages, factsheet embedded as PDF
  04  AMEND of 02: the official NAV of the CHF class on 2025-11-04 corrected
  05  a delivery sent by mistake (NAV of 2025-11-06) ...
  06  ... and its DELETE

data/bad/ holds files a loader must not accept: cut off, wrong element order, unknown sender,
and a second copy of 02 (same document ID: skipped, not loaded twice).
"""
import copy
import pathlib
import random
import sys
from datetime import date
from decimal import Decimal as D

from lxml import etree

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "FundsXML_Files" / "4.2.9" / "realistic"))
import make_realistic as R  # noqa: E402  (the fictional funds, parties and emitters)

SUPPLIER = "EXAMPLE-AM"
SCHEMA = "https://github.com/fundsxml/schema/releases/download/4.2.9/FundsXML.xsd"
XSI = "http://www.w3.org/2001/XMLSchema-instance"
NAV_DAYS = [date(2025, 11, 3), date(2025, 11, 4), date(2025, 11, 5)]
UMBRELLA = {"lei": R.make_lei("FNDUMBRELLA1"), "name": "Example Invest SICAV", "short": "EX Invest SICAV"}


def doc_id(kind, day, suffix=""):
    return f"{SUPPLIER}-{kind}-{day.isoformat()}{suffix}"


# ---------------------------------------------------------------------------------------------
# small XML helpers (lxml, so that parts of the realistic files can be rearranged)
# ---------------------------------------------------------------------------------------------

def E(tag, *children, text=None, **attrib):
    el = etree.Element(tag, {k: v for k, v in attrib.items() if v is not None})
    if text is not None:
        el.text = "true" if text is True else "false" if text is False else format(text, "f") \
            if isinstance(text, D) else str(text)
    for c in children:
        if c is not None:
            el.append(c)
    return el


def amounts(tag, *pairs):
    return E(tag, *[E("Amount", text=v, ccy=c, **flags) for v, c, flags in pairs])


def root(doc, content_date, generated, operation="INITIAL", related=None, comment=None):
    r = etree.Element("FundsXML4", nsmap={"xsi": XSI})
    r.set(f"{{{XSI}}}noNamespaceSchemaLocation", SCHEMA)
    ctl = E("ControlData",
            E("UniqueDocumentID", text=doc), E("DocumentGenerated", text=generated), E("Version", text="4.2.9"),
            E("ContentDate", text=content_date.isoformat()),
            E("DataSupplier", E("SystemCountry", text="AT"), E("Short", text=SUPPLIER),
              E("Name", text=R.MANCO["name"]), E("Type", text="Asset Manager")),
            E("DataOperation", text=operation),
            E("RelatedDocumentIDs", E("RelatedDocumentID", text=related)) if related else None,
            E("Language", text="en"))
    r.append(ctl)
    return r, comment


def write(path, tree_and_comment):
    r, comment = tree_and_comment
    etree.indent(r, space="  ")
    text = etree.tostring(r, encoding="unicode")
    head = '<?xml version="1.0" encoding="UTF-8"?>\n'
    head += f"<!-- Synthetic sample: {comment or 'fictional funds and identifiers'}. Generated by make_samples.py. -->\n"
    path.write_text(head + text + "\n", encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(HERE.parent))


def parse(writer):
    return etree.fromstring(writer.text())


# ---------------------------------------------------------------------------------------------
# the four funds of the realistic samples
# ---------------------------------------------------------------------------------------------

def prepare(builder):
    """Build one realistic fund, with the same ordering and transaction ids as make_realistic.render."""
    doc, fund, classes, breakdowns, risk, benchmark = builder()
    seq = 0
    for t in sorted(doc.transactions, key=lambda t: (t["date"], t["kind"] == "CASH")):
        if not t["id"] or t["kind"] != "CASH":
            seq += 1
            t["id"] = t["id"] or f"TRX-2025-10-{seq:04d}"
    doc.transactions.sort(key=lambda t: (t["date"], t["id"]))
    doc.earnings.sort(key=lambda e: (e["pay"], e["asset"]["uid"]))
    R.self_check(doc, classes)
    for c in classes:
        c["full_name"] = fund["name"] + " " + c["name_suffix"]
    return {"doc": doc, "fund": fund, "classes": classes, "breakdowns": breakdowns, "risk": risk,
            "benchmark": benchmark}


def funds():
    f = {"GE": prepare(R.global_equity), "EB": prepare(R.euro_bond),
         "MA": prepare(R.multi_asset), "FF": prepare(R.fund_of_funds)}
    # One AssetMasterData for the whole file: an asset with an ISIN appears once, whatever fund holds
    # it. Cash accounts, fee accruals and OTC contracts have no ISIN and belong to one fund each.
    # The UniqueIDs are the sender's own: fund code and a number, valid in this file only.
    registry = {}
    for code, x in f.items():
        n = 0
        for a in x["doc"].assets.values():
            if a.get("isin") and a["isin"] in registry:
                a["uid"] = registry[a["isin"]]["uid"]
                continue
            n += 1
            a["uid"] = f"{code}_{n:04d}"
            registry[a.get("isin") or (code, a["key"])] = a
    return f, list(registry.values())


def fund_element(x, benchmark=True):
    w = R.Writer()
    R.emit_fund(w, x["doc"], x["fund"], x["classes"], x["breakdowns"], x["risk"],
                x["benchmark"] if benchmark else None)
    return parse(w)


def language_names(names, de):
    """Names in a second language: <LanguageNames><Name language="de">."""
    official = names.findtext("OfficialName")
    names.append(E("LanguageNames", E("Name", text=official, language="en"), E("Name", text=de, language="de")))


def subfund(x, de_name):
    """A realistic single fund turned into a subfund of the umbrella."""
    fund = fund_element(x, benchmark=False)
    sub = E("Subfund")
    for tag in ("Identifiers", "Names", "Currency"):
        sub.append(fund.find(tag))
    language_names(sub.find("Names"), de_name)
    static, single = fund.find("FundStaticData"), fund.find("SingleFund/SingleFundStaticData")
    s = E("SubfundStaticData", copy.deepcopy(static.find("InceptionDate")))
    for tag in ("Managers", "Policies", "FundOfFundFlag", "SocialResponsibleFlag", "ManagementType",
                "PricePublishedFlag"):
        s.append(single.find(tag))
    s.append(static.find("OpenClosedEnded"))
    sub.append(s)
    dyn = fund.find("FundDynamicData")
    dyn.tag = "SubfundDynamicData"
    sub.append(dyn)
    sub.append(fund.find("SingleFund/ShareClasses"))
    return sub


def umbrella(f):
    """Example Invest SICAV: Global Equity and Euro Bond as subfunds, one fund element."""
    ge = fund_element(f["GE"])
    static = ge.find("FundStaticData")
    static.find("DomicileCountry").text = "LU"
    static.find("ListedLegalStructure").text = "UCITS"
    # the benchmark of the umbrella's static data is no longer referenced by any dynamic data
    bm = static.find("Benchmarks")
    static.remove(bm)
    tna = f["GE"]["doc"].tna + f["EB"]["doc"].tna
    names = E("Names", E("OfficialName", text=UMBRELLA["name"]), E("ShortName", text=UMBRELLA["short"]))
    language_names(names, "Example Invest SICAV (Umbrella)")
    return E("Fund",
             E("Identifiers", E("LEI", text=UMBRELLA["lei"])), names,
             E("Currency", text="EUR"), E("SingleFundFlag", text=False), static,
             E("FundDynamicData", E("TotalAssetValues", E("TotalAssetValue",
                                                          E("NavDate", text=R.AS_OF.isoformat()),
                                                          E("TotalAssetNature", text="OFFICIAL"),
                                                          amounts("TotalNetAssetValue", (tna, "EUR", {}))))),
             E("Subfunds", subfund(f["GE"], "Beispiel Global Aktien"), subfund(f["EB"], "Beispiel Euro Anleihen")))


def eet(x):
    """A small EET 1.1.3 per share class: the SFDR facts most distributors ask for."""
    out = []
    for c in x["classes"]:
        out.append(E("EET1.1.3",
            E("DataSetInformation",
              E("DataSetInformation", E("Version", text="V1.1.3"), E("FileGeneration", text=R.GENERATED),
                E("DataReporting", E("SFDRPreContractual", text="Y"), E("SFDRPeriodic", text="Y"),
                  E("SFDREntityLevel", text="N"), E("MiFID", text="Y"), E("IDD", text="Y"))),
              E("ManufacturerInformation", E("Name", text=R.MANCO["name"]), E("CodeType", text="L"),
                E("Code", text=R.MANCO["lei"]), E("GeneralReferenceDate", text=R.AS_OF.isoformat())),
              E("ManufacturerWebsiteInformationStewardshipAndEngagement",
                text="https://www.example.com/stewardship")),
            E("GeneralFinancialInstrumentInformation",
              E("IdentifyingData", text=c["isin"]), E("TypeOfIdentification", text="1"),
              E("Name", text=c["full_name"]), E("Currency", text=c["ccy"])),
            E("MainCriterias", E("SFDRProductType", text=x["fund"]["sfdr"]),
              E("ConsidersPrincipleAdverseImpact", text="Y")),
            E("MiFIDIDDTargetMarket", E("EndClientSustainabilityPreferences_Considered", text="Y")),
            E("ScreeningCriteria", E("ExistingNegativeScreeningStrategy", text="Y"))))
    return out


def month_end():
    f, assets = funds()
    r = root(doc_id("MONTHEND", R.AS_OF), R.AS_OF, R.GENERATED,
             comment="month end 2025-10-31 of four fictional funds (umbrella with two subfunds, two single funds)")
    r[0].append(E("Funds", umbrella(f), fund_element(f["MA"]), fund_element(f["FF"])))
    doc = R.Doc(0)
    for a in assets:
        doc.assets[a["uid"]] = a
    w = R.Writer()
    R.emit_assets(w, doc)
    r[0].append(parse(w))
    w = R.Writer()
    R.emit_regulatory(w, f["MA"]["doc"], f["MA"]["fund"], f["MA"]["classes"])
    reg = parse(w)
    reg.find("DirectReporting").append(E("EET1.1.3", *eet(f["GE"]), *eet(f["MA"])))
    r[0].append(reg)
    return r, f


# ---------------------------------------------------------------------------------------------
# daily NAVs, correction, mistake and its deletion
# ---------------------------------------------------------------------------------------------

def nav_series(f):
    """Per share class and day: (official NAV, estimated NAV, shares); deterministic small moves."""
    rng = random.Random(2025_11)
    series = {}
    for code, x in f.items():
        for c in x["classes"]:
            nav, rows = c["nav"], []
            for d in NAV_DAYS + [date(2025, 11, 6)]:
                nav = R.q(nav * (1 + D(rng.randrange(-60, 61)) / 10000))
                estimate = R.q(nav * (1 + D(rng.randrange(-8, 9)) / 10000))
                rows.append((d, nav, estimate))
            series[c["isin"]] = rows
    return series


def tav(day, nature, sc_ccy_tna, eur_tna, ccy, shares=None):
    if ccy == "EUR":
        tna = amounts("TotalNetAssetValue", (eur_tna, "EUR", {}))
    else:
        tna = amounts("TotalNetAssetValue", (sc_ccy_tna, ccy, {"isShareClassCcy": "true"}),
                      (eur_tna, "EUR", {"isFundCcy": "true"}))
    return E("TotalAssetValue", E("NavDate", text=day.isoformat()), E("TotalAssetNature", text=nature), tna,
             E("SharesOutstanding", text=shares) if shares is not None else None)


def nav_fund(x, series, days, correct=None, sub=False):
    """One fund (or subfund) with its share classes: prices and net assets per day and nature."""
    fund, classes = x["fund"], x["classes"]
    sc_elems, fund_tna = [], {}
    for c in classes:
        prices, tavs = E("Prices"), E("TotalAssetValues")
        for d, nav, estimate in series[c["isin"]]:
            if d not in days:
                continue
            if correct and correct[0] == c["isin"] and correct[1] == d:
                nav = correct[2]
            for nature, value in (("ESTIMATED", estimate), ("OFFICIAL", nav)):
                prices.append(E("Price", E("ActionCode", text="C"), E("NavDate", text=d.isoformat()),
                                E("PriceCurrency", text=c["ccy"]), E("PriceNature", text=nature),
                                E("NavPrice", text=value)))
                ccy_tna = R.q(value * c["shares"])
                eur_tna = ccy_tna if c["ccy"] == "EUR" else R.q(ccy_tna / R.FX[c["ccy"]])
                tavs.append(tav(d, nature, ccy_tna, eur_tna, c["ccy"], c["shares"]))
                fund_tna[(d, nature)] = fund_tna.get((d, nature), D(0)) + eur_tna
        sc_elems.append(E("ShareClass", E("Identifiers", E("ISIN", text=c["isin"])),
                          E("Names", E("OfficialName", text=c["full_name"])), E("Currency", text=c["ccy"]),
                          prices, tavs))
    dyn = E("SubfundDynamicData" if sub else "FundDynamicData",
            E("TotalAssetValues", *[tav(d, n, None, v, "EUR") for (d, n), v in sorted(fund_tna.items())]))
    head = [E("Identifiers", E("LEI", text=fund["lei"])), E("Names", E("OfficialName", text=fund["name"])),
            E("Currency", text="EUR")]
    if sub:
        return E("Subfund", *head, dyn, E("ShareClasses", *sc_elems)), fund_tna
    return E("Fund", *head, E("SingleFundFlag", text=True), dyn,
             E("SingleFund", E("ShareClasses", *sc_elems))), fund_tna


def nav_delivery(f, series, days, doc, operation="INITIAL", related=None, correct=None, comment=None,
                 generated=None):
    generated = generated or f"{days[-1].isoformat()}T18:30:00"
    r = root(doc, days[-1], generated, operation, related, comment)
    ge, ge_tna = nav_fund(f["GE"], series, days, correct, sub=True)
    eb, eb_tna = nav_fund(f["EB"], series, days, correct, sub=True)
    umb_tna = {k: ge_tna[k] + eb_tna[k] for k in ge_tna}
    umb = E("Fund", E("Identifiers", E("LEI", text=UMBRELLA["lei"])),
            E("Names", E("OfficialName", text=UMBRELLA["name"])), E("Currency", text="EUR"),
            E("SingleFundFlag", text=False),
            E("FundDynamicData", E("TotalAssetValues", *[tav(d, n, None, v, "EUR") for (d, n), v in sorted(umb_tna.items())])),
            E("Subfunds", ge, eb))
    r[0].append(E("Funds", umb, nav_fund(f["MA"], series, days, correct)[0],
                  nav_fund(f["FF"], series, days, correct)[0]))
    return r


def documents(f):
    """Prospectus as link, KIDs in English and German as links, PRIIPs KID and factsheet embedded."""
    r = root(doc_id("DOCUMENTS", date(2025, 11, 3)), date(2025, 11, 3), "2025-11-03T07:00:00",
             comment="fund documents (links and embedded PDFs); the PDFs say they are fictitious")
    docs = E("Documents")
    for d in R.fund_documents():        # the multi-asset fund, as in Fund-Documents_2025-10.xml
        w = R.Writer()
        R.emit_document(w, d)
        docs.append(parse(w))
    ge = f["GE"]
    for lang, title in (("en", "Key Information Document"), ("de", "Basisinformationsblatt")):
        for c in ge["classes"]:
            fname = f"EX-Global-Equity_PRIIPs-KID_{c['isin']}_2025-02_{lang}.pdf"
            docs.append(E("Document",
                          E("Type", E("ListedType", text="PRIIPS-KID")), E("Version", text="2025-02"),
                          E("Language", text=lang), E("TranslationsAvailable", text=True),
                          E("PublicationCountries", *[E("Country", text=cc) for cc in (("AT", "DE") if lang == "de" else ("AT", "DE", "IT"))]),
                          E("ShareClasses", E("ShareClass", E("Identifiers", E("ISIN", text=c["isin"])),
                                              E("Name", text=c["full_name"]), E("Currency", text=c["ccy"]))),
                          E("Name", text=f"{title} {c['full_name']}"), E("FileName", text=fname),
                          E("ForPublicUsage", text=True), E("Format", text="application/pdf"),
                          E("Signature", text="No"), E("CreationDate", text="2025-02-14"),
                          E("ExpirationDate", text="2026-02-13"),
                          E("SizeInBytes", text=180000 + len(fname) * 37),
                          E("DocumentURL", text=f"https://www.example.com/funds/{ge['fund']['lei']}/documents/{fname}")))
    r[0].append(docs)
    return r


def main():
    out, bad = HERE / "in", HERE / "bad"
    for d in (out, bad):
        d.mkdir(exist_ok=True)
        for old in d.glob("*.xml"):
            old.unlink()
    me, f = month_end()
    write(out / "01_month-end_2025-10-31.xml", me)
    series = nav_series(f)
    nav_id = doc_id("NAV", NAV_DAYS[-1])
    write(out / "02_nav_2025-11-05.xml",
          nav_delivery(f, series, NAV_DAYS, nav_id, comment="daily NAVs 2025-11-03 to 2025-11-05, estimated and official"))
    write(out / "03_documents_2025-11-03.xml", documents(f))
    chf = next(c for c in f["MA"]["classes"] if c["ccy"] == "CHF")
    wrong = next(n for d, n, _ in series[chf["isin"]] if d == NAV_DAYS[1])
    write(out / "04_nav_2025-11-05_amend.xml",
          nav_delivery(f, series, NAV_DAYS, nav_id + "-AMEND-1", "AMEND", nav_id,
                       correct=(chf["isin"], NAV_DAYS[1], R.q(wrong * D("1.0125"))),
                       comment=f"correction of {nav_id}: official NAV of {chf['isin']} on 2025-11-04",
                       generated="2025-11-06T09:15:00"))
    mistake = doc_id("NAV", date(2025, 11, 6))
    write(out / "05_nav_2025-11-06_sent-by-mistake.xml",
          nav_delivery(f, series, [date(2025, 11, 6)], mistake, comment="sent by mistake, deleted by file 06"))
    write(out / "06_nav_2025-11-06_delete.xml",
          root(mistake + "-DELETE", date(2025, 11, 6), "2025-11-06T19:05:00", "DELETE", mistake,
               comment=f"takes back {mistake}"))

    # --- files a loader must reject (or skip)
    good = (out / "02_nav_2025-11-05.xml").read_text(encoding="utf-8")
    (bad / "cut-off.xml").write_text(good[: len(good) // 2], encoding="utf-8", newline="\n")
    swapped = good.replace(nav_id, doc_id("NAV", NAV_DAYS[-1], "-ORDER"), 1)
    first_sc = swapped.index("<ShareClass>")
    names_at = swapped.index("<Names>", first_sc)
    ccy_at = swapped.index("<Currency>", first_sc)
    ccy_end = swapped.index("</Currency>", ccy_at) + len("</Currency>")
    names_end = swapped.index("</Names>", names_at) + len("</Names>")
    indent = swapped[swapped.rindex("\n", 0, names_at) + 1:names_at]
    swapped = (swapped[:names_at] + swapped[ccy_at:ccy_end] + "\n" + indent + swapped[names_at:names_end]
               + swapped[ccy_end:])
    (bad / "wrong-order.xml").write_text(swapped, encoding="utf-8", newline="\n")
    (bad / "unknown-sender.xml").write_text(
        good.replace(nav_id, doc_id("NAV", NAV_DAYS[-1], "-OTHER"), 1)
            .replace(f"<Short>{SUPPLIER}</Short>", "<Short>OTHER-AM</Short>", 1), encoding="utf-8", newline="\n")
    (bad / "duplicate-of-02.xml").write_text(good, encoding="utf-8", newline="\n")
    for p in sorted(bad.glob("*.xml")):
        print("wrote", p.relative_to(HERE.parent))


if __name__ == "__main__":
    main()
